-- error messages, tracebacks and the standalone interpreter's reporting:
-- every byte of what a user sees when things go wrong
local function show(...)
  local t = table.pack(...)
  for i = 1, t.n do if type(t[i]) == "table" then t[i] = "<a table>" end end   -- never an address
  print(t.n, table.unpack(t, 1, t.n))
end
