-- the io library against the filesystem and stdin: open modes, reads by
-- format, seek, lines, buffering, errors with their errno text and number
local function show(...) print(select("#", ...), ...) end
show(io.type(io.stdin), io.type(io.stdout), io.type(42), io.type(io.open("t.lua")))
-- stdin: the host feeds four lines, the last without a newline
show(io.read("l"))
show(io.read("L"))
show(io.read("n", "n", "n"))
show(io.read("l"))
show(io.read(5))
show(io.read("a"))
show(io.read("l"), io.read(0), io.read("a"))
-- writing and reading back
local f = assert(io.open("data/a.txt", "w"))
show(f:write("hello\n", 42, " ", 1.5, "\n", "world") == f)
show(f:seek("cur"), f:seek("set", 2), f:seek("end"), f:seek("end", -3))
show(f:close())
show(pcall(f.write, f, "x"))
show(io.type(f), (tostring(f):gsub("%(.*%)", "(...)")))
f = assert(io.open("data/a.txt"))
show(f:read("l", "n", "n", "l", "a"))
show(f:read("a"), f:read("l"), f:read(0), f:read("n"))
f:close()
for l in io.lines("data/a.txt") do io.write("[", l, "]") end print()
for a, b in io.lines("data/a.txt", 2, "l") do io.write("<", a, "|", tostring(b), ">") end print()
show(pcall(io.lines, "data/missing.txt"))
f = assert(io.open("data/a.txt", "a"))
f:write("\nappended")
f:close()
show(io.open("data/a.txt"):read("a"))
f = assert(io.open("data/a.txt", "r+"))
f:seek("set", 1) f:write("EL") f:seek("set") show(f:read("l")) f:close()
f = assert(io.open("data/a.txt", "w+"))
f:write("abc") f:seek("set") show(f:read("a")) f:close()
f = assert(io.open("data/gap.bin", "wb"))
f:seek("set", 5) f:write("x") f:close()
f = io.open("data/gap.bin", "rb") show(#f:read("a"), f:read("a"):byte(1, -1)) f:close()
-- modes and errors
show(pcall(io.open, "data/a.txt", "x"))
show(pcall(io.open, "data/a.txt", "rw"))
show(io.open("nonexistent/dir/file", "w"))
show(io.open("data", "w"))
show(io.type(io.open("data")), io.open("data"):read("l"))
show(io.open(""))
show(os.remove("data/missing"))
show(os.rename("data/missing", "data/other"))
show(os.remove("data"))
show(os.rename("data/a.txt", "data/b.txt"), io.open("data/a.txt"), io.open("data/b.txt") ~= nil)
show(os.remove("data/b.txt"), os.remove("data/gap.bin"), io.open("data") ~= nil)
-- tmpfile and tmpname (the random part masked)
local t = io.tmpfile()
t:write("temporary") t:seek("set") show(t:read("a")) t:close()
local name = os.tmpname()
show((name:gsub("[%w_]+$", "X")), io.open(name) ~= nil, os.remove(name))
-- buffering and output switching
show(io.stdout:setvbuf("full", 4), io.write("buffered") == io.stdout, io.stdout:flush() == io.stdout)
io.stdout:setvbuf("line")
show(io.output():setvbuf("no"))
io.stdout:setvbuf("line")
local o = io.output("data/out.txt")
io.write("to a file\n")
io.output():close()
show(pcall(io.write, "x"))
io.output(io.stdout)
show(io.open("data/out.txt"):read("a"))
show(io.type(io.input("data/out.txt")), io.read("l"), io.read("l"))
io.input(io.stdin)
show(pcall(io.input, "data/missing.txt"))
show(pcall(io.close))
show(io.stdout:close())
io.stderr:write("to stderr\n")
show(pcall(io.read, "x"))
show(pcall(io.read, "*z"))
local h = io.open("data/out.txt") h:close()
show(pcall(h.read, h), pcall(h.lines, h), pcall(io.close, h))
show(io.open("data/out.txt"):lines()())
show(pcall(function() for l in io.lines("data/out.txt", "x") do end end))
show(#io.open("t.lua"):read("a") > 100)
-- last: the directory goes only once it is empty
show(os.remove("data"), os.remove("data/out.txt"), os.remove("data"), os.remove("data"), io.open("data"))
